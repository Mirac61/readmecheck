package rules

import (
	"fmt"
	"strings"
)

// ReportMarkdown renders the same deterministic report shown in the UI as a
// portable Markdown checklist.
func ReportMarkdown(report Report) string {
	var builder strings.Builder
	repository := report.Repository
	name := "repository"
	url := ""
	if repository != nil {
		name = repository.FullName
		if name == "" && repository.Ref.Owner != "" {
			name = repository.Ref.FullName()
		}
		url = repository.HTMLURL
	}

	builder.WriteString("# README check: ")
	builder.WriteString(name)
	builder.WriteString("\n\n")
	if url != "" {
		builder.WriteString(url)
		builder.WriteString("\n\n")
	}
	builder.WriteString(fmt.Sprintf("**Score:** %d/100 (grade %s)  \n", report.Score, report.Grade))
	builder.WriteString(fmt.Sprintf("**Results:** %d passed, %d failed, %d skipped  \n", report.Counts.Passed, report.Counts.Failed, report.Counts.Skipped))
	builder.WriteString("**Checked:** ")
	builder.WriteString(report.GeneratedAt.UTC().Format("2006-01-02 15:04 UTC"))
	builder.WriteString("  \n")
	builder.WriteString("**External links:** ")
	if report.ExternalLinksChecked {
		builder.WriteString("checked")
	} else {
		builder.WriteString("not checked")
	}
	builder.WriteString("\n\n")
	if repository != nil && strings.TrimSpace(repository.Description) != "" {
		builder.WriteString("> ")
		builder.WriteString(strings.ReplaceAll(strings.TrimSpace(repository.Description), "\n", " "))
		builder.WriteString("\n\n")
	}
	if repository != nil {
		builder.WriteString(fmt.Sprintf("- **Stars:** %d\n", repository.Stars))
		if repository.License != nil {
			builder.WriteString("- **License:** ")
			builder.WriteString(repository.License.Name)
			builder.WriteString("\n")
		}
		if repository.Archived {
			builder.WriteString("- **Status:** archived\n")
		}
		if repository.LatestRelease != nil && repository.LatestRelease.TagName != "" {
			builder.WriteString("- **Latest release:** ")
			builder.WriteString(repository.LatestRelease.TagName)
			builder.WriteString("\n")
		}
	}

	builder.WriteString("\n## Category scores\n\n")
	builder.WriteString("| Category | Score | Passed | Failed | Skipped |\n")
	builder.WriteString("| --- | ---: | ---: | ---: | ---: |\n")
	for _, category := range report.Categories {
		score := "—"
		if category.Applicable {
			score = fmt.Sprintf("%d", category.Score)
		}
		builder.WriteString(fmt.Sprintf("| %s | %s | %d | %d | %d |\n",
			category.Label, score, category.Passed, category.Failed, category.Skipped))
	}

	builder.WriteString("\n## Checklist\n")
	for _, category := range Categories() {
		results := report.ResultsFor(category)
		if len(results) == 0 {
			continue
		}
		builder.WriteString("\n### ")
		builder.WriteString(CategoryLabel(category))
		builder.WriteString("\n\n")
		for _, result := range results {
			status := "PASS"
			switch result.Status {
			case StatusFail:
				status = "FAIL"
			case StatusSkipped:
				status = "SKIP"
			}
			builder.WriteString(fmt.Sprintf("- **%s** — `%s` · %s · %s · weight %d\n",
				status, result.Rule.ID, result.EffectiveSeverity(), result.Rule.Title, result.Rule.Weight))
			if result.Detail != "" {
				builder.WriteString("  - ")
				builder.WriteString(result.Detail)
				builder.WriteString("\n")
			}
			for _, evidence := range result.Evidence {
				builder.WriteString("  - Evidence: ")
				builder.WriteString(strings.ReplaceAll(evidence, "\n", " "))
				builder.WriteString("\n")
			}
			if result.Status != StatusPass {
				builder.WriteString("  - **Why it matters:** ")
				builder.WriteString(result.Rule.Why)
				builder.WriteString("\n")
				builder.WriteString("  - **How to fix:** ")
				builder.WriteString(result.Rule.Fix)
				builder.WriteString("\n")
			}
		}
	}

	builder.WriteString("\n---\n\n")
	builder.WriteString("Generated by readmecheck. Rules and rationale: docs/criteria.md.\n")
	return builder.String()
}
